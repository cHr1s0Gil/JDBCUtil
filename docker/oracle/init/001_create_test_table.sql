ALTER SESSION SET CONTAINER = XEPDB1;

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE JDBCUTIL_USER.JDBCUTIL_ORACLE_BENCHMARK (
            RECORD_KEY NUMBER(10) PRIMARY KEY,
            RECORD_VALUE NUMBER(10) NOT NULL
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

MERGE INTO JDBCUTIL_USER.JDBCUTIL_ORACLE_BENCHMARK target
USING (
    SELECT 1 AS RECORD_KEY, 100 AS RECORD_VALUE
    FROM DUAL
) source
ON (target.RECORD_KEY = source.RECORD_KEY)
WHEN MATCHED THEN
    UPDATE SET target.RECORD_VALUE = source.RECORD_VALUE
WHEN NOT MATCHED THEN
    INSERT (RECORD_KEY, RECORD_VALUE)
    VALUES (source.RECORD_KEY, source.RECORD_VALUE);

COMMIT;

